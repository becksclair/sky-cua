#!/usr/bin/env bash
# Drive a self-owned, isolated sky-cua instance on a Linux host.
#
# The instance is a second sky-cua-service daemon on a private xpra/Openbox X11
# display (the shipped isolated-desktop lane), built from this checkout into a
# scratch tree. It never touches the user's running daemon, MCP registrations,
# installed runtime, config, or desktop session.
#
# Usage: verify.sh <command>
#   sync      copy this checkout's tracked + untracked-unignored files to the host
#   build     release-build sky-cua-client and sky-cua-service into the scratch target
#   launch    bring the private desktop and the isolated daemon up; wait until usable
#   doctor    read-only: is this instance worth driving?
#   drive     run the MCP journey (default: zenity entry round trip); writes evidence
#   teardown  stop the private desktop and the isolated daemon; verify nothing is left
#   cli ARGS  run sky-cua-client ARGS against the isolated instance (operator CLI:
#             health, doctor, list-apps, list-windows, get-app-state --name X, ...)
#   pull      copy the host evidence for the current run to <repo>/artifacts/verify-sky-cua/
#   all       sync build launch doctor drive teardown pull (teardown runs even on failure)
#
# Environment:
#   VERIFY_HOST     ssh host that runs the instance (default: asgard). "local" means
#                   this machine, which must be Linux with a graphical user session.
#   VERIFY_DISPLAY  private X display owned by this run (default: :147)
#   VERIFY_RUN_ID   evidence run id (default: generated by launch, stored in the root)
set -euo pipefail

VERIFY_HOST="${VERIFY_HOST:-asgard}"
VERIFY_DISPLAY="${VERIFY_DISPLAY:-:147}"
DISPLAY_NUMBER="${VERIFY_DISPLAY#:}"
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
SKILL_REL=".agents/skills/verify-sky-cua"
# Root of every file this skill creates on the host. Relative to $HOME so the
# same path works for the operator and the host.
ROOT_REL=".cache/sky-cua-verify"

die() {
  printf 'verify-sky-cua: %s\n' "$*" >&2
  exit 1
}
log() { printf 'verify-sky-cua: %s\n' "$*" >&2; }

repo_root() { (cd -- "$SCRIPT_DIR/../../../.." && pwd); }

# --------------------------------------------------------------------------
# Operator side: forward to the host unless VERIFY_HOST=local.
# --------------------------------------------------------------------------

remote() {
  # Forward one command to the host copy of this script.
  local cmd="$1"
  ssh -o BatchMode=yes "$VERIFY_HOST" \
    "VERIFY_HOST=local VERIFY_DISPLAY='$VERIFY_DISPLAY' VERIFY_RUN_ID='${VERIFY_RUN_ID:-}' \
     VERIFY_SRC=\"\$HOME/$ROOT_REL/src\" bash \"\$HOME/$ROOT_REL/src/$SKILL_REL/scripts/verify.sh\" $cmd"
}

cmd_sync() {
  local repo
  repo="$(repo_root)"
  if [[ "$VERIFY_HOST" == "local" ]]; then
    log "VERIFY_HOST=local builds this checkout in place; nothing to sync"
    return 0
  fi
  local list
  list="$(mktemp)"
  # Tracked + untracked-not-ignored files: exactly the working tree under test.
  # .claude/skills is a host-specific absolute symlink; skip it.
  (cd "$repo" && git ls-files -co --exclude-standard) | grep -vx '.claude/skills' >"$list"
  grep -qx 'Cargo.toml' "$list" || die "file list from $repo has no Cargo.toml; refusing to sync"
  ssh -o BatchMode=yes "$VERIFY_HOST" "mkdir -p \"\$HOME/$ROOT_REL/src\""
  rsync -a --files-from="$list" "$repo/" "$VERIFY_HOST:$ROOT_REL/src/"
  # Mirror deletions: drop host files that are no longer in the working tree.
  rsync -a "$list" "$VERIFY_HOST:$ROOT_REL/src-files.txt"
  ssh -o BatchMode=yes "$VERIFY_HOST" "cd \"\$HOME/$ROOT_REL/src\" && \
    comm -23 <(find . -type f | sed 's|^\./||' | LC_ALL=C sort) \
             <(LC_ALL=C sort ../src-files.txt) | tr '\n' '\0' | xargs -0 -r rm -f"
  local rev dirty
  rev="$(git -C "$repo" rev-parse HEAD)"
  dirty="$(git -C "$repo" status --porcelain | wc -l | tr -d ' ')"
  ssh -o BatchMode=yes "$VERIFY_HOST" \
    "printf 'rev=%s\ndirty_paths=%s\nsynced_at=%s\n' '$rev' '$dirty' \"\$(date -u +%FT%TZ)\" > \"\$HOME/$ROOT_REL/src-stamp.txt\""
  log "synced $(wc -l <"$list" | tr -d ' ') files at $rev (dirty paths: $dirty) to $VERIFY_HOST:~/$ROOT_REL/src"
  rm -f "$list"
}

cmd_pull() {
  local repo run_id
  repo="$(repo_root)"
  if [[ "$VERIFY_HOST" == "local" ]]; then
    run_id="${VERIFY_RUN_ID:-$(cat "$HOME/$ROOT_REL/current-run" 2>/dev/null || true)}"
    [[ -n "$run_id" ]] || die "no run id; set VERIFY_RUN_ID or run launch first"
    mkdir -p "$repo/artifacts/verify-sky-cua"
    cp -a "$HOME/$ROOT_REL/runs/$run_id" "$repo/artifacts/verify-sky-cua/"
  else
    run_id="${VERIFY_RUN_ID:-$(ssh -o BatchMode=yes "$VERIFY_HOST" "cat \"\$HOME/$ROOT_REL/current-run\"")}"
    [[ -n "$run_id" ]] || die "no run id on $VERIFY_HOST; set VERIFY_RUN_ID or run launch first"
    mkdir -p "$repo/artifacts/verify-sky-cua"
    rsync -a "$VERIFY_HOST:$ROOT_REL/runs/$run_id" "$repo/artifacts/verify-sky-cua/"
  fi
  log "evidence: $repo/artifacts/verify-sky-cua/$run_id"
  printf '%s\n' "$repo/artifacts/verify-sky-cua/$run_id"
}

# --------------------------------------------------------------------------
# Host side (Linux).
# --------------------------------------------------------------------------

host_init() {
  [[ "$(uname -s)" == "Linux" ]] || die "the isolated lane needs a Linux host; set VERIFY_HOST to one"
  ROOT="$HOME/$ROOT_REL"
  SRC="${VERIFY_SRC:-$(repo_root)}"
  TARGET="$ROOT/target"
  CLIENT="$TARGET/release/sky-cua-client"
  SERVICE="$TARGET/release/sky-cua-service"
  : "${XDG_RUNTIME_DIR:=/run/user/$(id -u)}"
  export XDG_RUNTIME_DIR
  ISOLATED_SOCKET="$XDG_RUNTIME_DIR/sky-cua/service-isolated-${DISPLAY_NUMBER}.sock"
}

current_run_dir() {
  local run_id="${VERIFY_RUN_ID:-$(cat "$ROOT/current-run" 2>/dev/null || true)}"
  [[ -n "$run_id" ]] || die "no current run; run launch first"
  printf '%s\n' "$ROOT/runs/$run_id"
}

# Run a command with the isolated, hermetic client environment. Every inherited
# SKY_CUA_* key is dropped so a shell pin (for example SKY_CUA_BROWSER from
# ~/.bashrc) cannot leak into the instance.
isolated() {
  local -a strip=()
  local key
  while IFS='=' read -r key _; do
    [[ "$key" == SKY_CUA_* ]] && strip+=(-u "$key")
  done < <(env)
  mkdir -p "$ROOT/state" "$ROOT/config" "$ROOT/browser-sockets"
  env "${strip[@]}" -u WAYLAND_DISPLAY -u DISPLAY -u AT_SPI_BUS_ADDRESS \
    XDG_STATE_HOME="$ROOT/state" \
    XDG_CONFIG_HOME="$ROOT/config" \
    SKY_CUA_ISOLATED_DESKTOP=1 \
    SKY_CUA_ISOLATED_DESKTOP_DISPLAY="$VERIFY_DISPLAY" \
    SKY_CUA_ISOLATED_DESKTOP_RESOLUTION=1280x800 \
    SKY_CUA_ISOLATED_DESKTOP_VIEWER=none \
    SKY_CUA_ISOLATED_DESKTOP_LIFECYCLE=persistent \
    SKY_CUA_SURFACES=desktop \
    SKY_CUA_PHONE=0 \
    SKY_CUA_BROWSER_USE_SOCKET_DIR="$ROOT/browser-sockets" \
    SKY_CUA_SERVICE_PATH="$SERVICE" \
    SKY_CUA_REPO_ROOT="$SRC" \
    "$@"
}

# PID of the daemon holding our isolated socket's singleton lock, or empty.
isolated_daemon_pid() {
  local pid
  pid="$(head -n 1 "${ISOLATED_SOCKET}.lock" 2>/dev/null | tr -dc '0-9' || true)"
  [[ -n "$pid" && -d "/proc/$pid" ]] || return 0
  [[ "$(readlink "/proc/$pid/exe" 2>/dev/null)" == "$SERVICE" ]] && printf '%s\n' "$pid"
}

# The user's own daemons: every sky-cua-service whose binary is not ours.
foreign_daemons() {
  local pid exe
  for pid in $(pgrep -x sky-cua-service || true); do
    exe="$(readlink "/proc/$pid/exe" 2>/dev/null || true)"
    [[ "$exe" == "$SERVICE" ]] && continue
    printf '%s %s\n' "$pid" "$exe"
  done
}

cmd_build() {
  host_init
  [[ -f "$SRC/Cargo.toml" ]] || die "no checkout at $SRC; run sync first"
  log "building release client + service from $SRC into $TARGET"
  (cd "$SRC" && CARGO_TARGET_DIR="$TARGET" nice -n 10 \
    cargo build --release -p sky-cua-client -p sky-cua-service)
  [[ -x "$CLIENT" && -x "$SERVICE" ]] || die "build did not produce $CLIENT and $SERVICE"
  log "built: $CLIENT"
}

cmd_launch() {
  host_init
  [[ -x "$CLIENT" && -x "$SERVICE" ]] || die "missing scratch binaries; run build first"
  local lock="/tmp/.X${DISPLAY_NUMBER}-lock"
  if [[ -e "$lock" ]] && ! xpra info "$VERIFY_DISPLAY" >/dev/null 2>&1; then
    die "$VERIFY_DISPLAY is held by a non-xpra server ($lock); pick another VERIFY_DISPLAY"
  fi
  local run_id="${VERIFY_RUN_ID:-run-$(date -u +%Y%m%d-%H%M%S)}"
  local run="$ROOT/runs/$run_id"
  mkdir -p "$run"
  printf '%s\n' "$run_id" >"$ROOT/current-run"
  cp "$ROOT/src-stamp.txt" "$run/src-stamp.txt" 2>/dev/null ||
    git -C "$SRC" rev-parse HEAD >"$run/src-stamp.txt"
  foreign_daemons >"$run/foreign-daemons-before.txt"
  ls -A "$XDG_RUNTIME_DIR/sky-cua" >"$run/runtime-dir-before.txt" 2>/dev/null || true
  log "run $run_id: ensuring private desktop $VERIFY_DISPLAY"
  isolated "$CLIENT" isolated-desktop ensure | tee "$run/launch-ensure.txt"
  # health connects to (and on first use spawns) the isolated daemon on its own
  # socket. Ready means the daemon answers health from this run's binary.
  log "starting the isolated daemon via health"
  local attempt
  for attempt in 1 2 3; do
    if isolated "$CLIENT" health >"$run/launch-health.json" 2>"$run/launch-health.err"; then
      break
    fi
    log "health attempt $attempt failed; retrying"
    sleep 2
  done
  local pid
  pid="$(isolated_daemon_pid)"
  [[ -n "$pid" ]] || die "no isolated daemon from $SERVICE holds ${ISOLATED_SOCKET}.lock; see $run/launch-health.err"
  printf '%s\n' "$pid" >"$run/isolated-daemon.pid"
  log "ready: display=$VERIFY_DISPLAY daemon_pid=$pid socket=$ISOLATED_SOCKET run=$run"
}

cmd_doctor() {
  host_init
  local ok=1 run pid
  run="$(current_run_dir 2>/dev/null || true)"
  printf 'host=%s kernel=%s\n' "$(hostname)" "$(uname -r)"
  printf 'src_stamp=%s\n' "$(tr '\n' ' ' <"$ROOT/src-stamp.txt" 2>/dev/null || echo missing)"
  if [[ -x "$CLIENT" && -x "$SERVICE" ]]; then
    printf 'binaries=ok built=%s\n' "$(date -u -r "$SERVICE" +%FT%TZ)"
    # Stale build: any synced Rust source newer than the service binary.
    if [[ -n "$(find "$SRC/crates" "$SRC/Cargo.lock" -newer "$SERVICE" -name '*.rs' -o -newer "$SERVICE" -name 'Cargo.*' 2>/dev/null | head -n 1)" ]]; then
      printf 'build_fresh=false (sources newer than binary; run build)\n'
      ok=0
    else
      printf 'build_fresh=true\n'
    fi
  else
    printf 'binaries=missing\n'
    ok=0
  fi
  # Structured desktop status; starts nothing.
  if [[ -x "$CLIENT" ]]; then
    isolated "$CLIENT" isolated-desktop status | sed 's/^/status./' || ok=0
  fi
  pid="$(isolated_daemon_pid)"
  if [[ -n "$pid" ]]; then
    printf 'isolated_daemon_pid=%s exe=%s\n' "$pid" "$(readlink "/proc/$pid/exe")"
    if isolated "$CLIENT" health >/dev/null 2>&1; then
      printf 'isolated_daemon_health=ok\n'
    else
      printf 'isolated_daemon_health=failed\n'
      ok=0
    fi
  else
    printf 'isolated_daemon_pid=none\n'
    ok=0
  fi
  printf 'current_run=%s\n' "${run:-none}"
  printf 'user_daemons_untouched_reference:\n'
  foreign_daemons | sed 's/^/  /'
  if [[ -n "$run" && -f "$run/foreign-daemons-before.txt" ]]; then
    if diff -q "$run/foreign-daemons-before.txt" <(foreign_daemons) >/dev/null; then
      printf 'user_daemons_unchanged=true\n'
    else
      printf 'user_daemons_unchanged=false\n'
      ok=0
    fi
  fi
  if ((ok)); then printf 'verdict=drivable\n'; else printf 'verdict=not-drivable\n'; return 1; fi
}

cmd_drive() {
  host_init
  local run
  run="$(current_run_dir)"
  [[ -n "$(isolated_daemon_pid)" ]] || die "isolated daemon is not up; run launch"
  isolated python3 "$SRC/$SKILL_REL/scripts/drive_isolated.py" \
    --client "$CLIENT" --run-dir "$run" --display "$VERIFY_DISPLAY" \
    --repo-scripts "$SRC/scripts" "$@"
}

cmd_cli() {
  host_init
  [[ -n "$(isolated_daemon_pid)" ]] || die "isolated daemon is not up; run launch"
  # Keep every operator call as evidence; teardown also reads these files to
  # delete runtime captures the call created.
  local run out
  run="$(current_run_dir)"
  out="$run/cli-$(date -u +%H%M%S)-${1:-none}.out"
  isolated "$CLIENT" "$@" | tee "$out"
  return "${PIPESTATUS[0]}"
}

cmd_teardown() {
  host_init
  local run status=0
  run="$(current_run_dir 2>/dev/null || true)"
  local pid
  pid="$(isolated_daemon_pid)"
  # Copy the isolated daemon log into the evidence before it can rotate away.
  if [[ -n "$run" ]]; then
    cp "$ROOT/state/sky-cua/daemon-service-isolated-${DISPLAY_NUMBER}.log" "$run/" 2>/dev/null || true
  fi
  # The client reaps xpra, the private buses, the AT-SPI owners, and the
  # isolated daemon (identity-checked via /proc/<pid>/exe); never pkill -f.
  isolated "$CLIENT" isolated-desktop stop || status=1
  if [[ -n "$pid" ]]; then
    local waited=0
    while [[ -d "/proc/$pid" ]] && ((waited < 50)); do
      sleep 0.1
      waited=$((waited + 1))
    done
    if [[ -d "/proc/$pid" && "$(readlink "/proc/$pid/exe" 2>/dev/null)" == "$SERVICE" ]]; then
      log "isolated daemon $pid survived stop; terminating it by pid"
      kill "$pid" 2>/dev/null || true
    fi
  fi
  # Remove only the runtime files this run created: AppShot images and source
  # captures named by ids recorded in steps.jsonl, unheld lock files for our
  # display, and the store directories when this run created them and they are
  # empty. The user's daemon shares $XDG_RUNTIME_DIR/sky-cua; touch nothing else.
  local rt="$XDG_RUNTIME_DIR/sky-cua"
  if [[ -n "$run" ]]; then
    python3 - "$run" "$rt" <<'PY'
import json, re, sys
from pathlib import Path
UUID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")
run, rt = Path(sys.argv[1]), Path(sys.argv[2])
stores = (rt / "appshots", rt / "captures")
def scalars(node, key=""):
    if isinstance(node, dict):
        for k, v in node.items():
            yield from scalars(v, k)
    elif isinstance(node, list):
        for v in node:
            yield from scalars(v, key)
    else:
        yield key, node
docs = []
steps = run / "steps.jsonl"
if steps.is_file():
    docs += [json.loads(line).get("response") for line in steps.read_text().splitlines()]
for out in sorted(run.glob("cli-*.out")):
    try:
        docs.append(json.loads(out.read_text()))
    except ValueError:
        pass
for doc in docs:
    for key, value in scalars(doc):
        if not isinstance(value, str) or not value:
            continue
        if value.startswith("/"):
            path = Path(value)
            if path.parent in stores:
                path.unlink(missing_ok=True)
                # A capture id also owns sibling variants (<id>-window.png,
                # <id>.webp); ids are UUIDs, so the prefix is unique.
                stem = path.name[:36]
                if UUID.fullmatch(stem):
                    for sibling in path.parent.glob(f"{stem}*"):
                        sibling.unlink(missing_ok=True)
        elif "/" in value:
            continue
        elif key == "filename":
            (rt / "appshots" / value).unlink(missing_ok=True)
        elif key == "snapshot_id" and UUID.fullmatch(value):
            for sibling in (rt / "captures").glob(f"{value}*"):
                sibling.unlink(missing_ok=True)
PY
  fi
  local lockfile
  for lockfile in "$rt/isolated-desktop-${DISPLAY_NUMBER}.lifecycle.lock" \
    "$rt/service-isolated-${DISPLAY_NUMBER}.sock.lifecycle.lock" \
    "$rt/service-isolated-${DISPLAY_NUMBER}.sock.lock"; do
    if [[ -e "$lockfile" ]]; then flock -n "$lockfile" rm -f "$lockfile" || true; fi
  done
  local store
  for store in appshots captures; do
    if [[ -n "$run" ]] && ! grep -qx "$store" "$run/runtime-dir-before.txt" 2>/dev/null; then
      rmdir "$rt/$store" 2>/dev/null || true
    fi
  done
  local residue=()
  xpra info "$VERIFY_DISPLAY" >/dev/null 2>&1 && residue+=("xpra session on $VERIFY_DISPLAY")
  [[ -e "/tmp/.X${DISPLAY_NUMBER}-lock" ]] && residue+=("/tmp/.X${DISPLAY_NUMBER}-lock")
  [[ -n "$(isolated_daemon_pid)" ]] && residue+=("isolated daemon")
  [[ -e "$XDG_RUNTIME_DIR/sky-cua/isolated-atspi-${DISPLAY_NUMBER}.json" ]] &&
    residue+=("isolated-atspi-${DISPLAY_NUMBER}.json")
  local report="teardown: residue=${residue[*]:-none}"
  if [[ -n "$run" ]]; then
    {
      printf '%s\n' "$report"
      # Reported, not enforced: the user's daemon may legitimately add entries.
      # shellcheck disable=SC2012  # plain runtime names; mirrors the launch snapshot
      printf 'runtime_dir_new_entries=%s\n' "$(comm -13 <(sort "$run/runtime-dir-before.txt" 2>/dev/null) \
        <(ls -A "$rt" 2>/dev/null | sort) | tr '\n' ' ')"
      printf 'user daemons after teardown:\n'
      foreign_daemons
    } >"$run/teardown.txt"
    if [[ -f "$run/foreign-daemons-before.txt" ]] &&
      ! diff -q "$run/foreign-daemons-before.txt" <(foreign_daemons) >/dev/null; then
      printf 'WARNING: user daemon set changed during the run\n' | tee -a "$run/teardown.txt" >&2
      status=1
    fi
  fi
  log "$report"
  ((${#residue[@]} == 0)) || status=1
  return "$status"
}

cmd_all() {
  cmd_sync
  if [[ "$VERIFY_HOST" == "local" ]]; then
    "$0" build && "$0" launch && "$0" doctor && "$0" drive
  else
    remote build && remote launch && remote doctor && remote drive
  fi
  local status=$?
  if [[ "$VERIFY_HOST" == "local" ]]; then "$0" teardown || status=1; else remote teardown || status=1; fi
  cmd_pull || status=1
  return "$status"
}

main() {
  local cmd="${1:-}"
  shift || true
  case "$cmd" in
    sync) cmd_sync ;;
    pull) cmd_pull ;;
    all)
      set +e
      cmd_all
      exit $?
      ;;
    build | launch | doctor | drive | teardown | cli)
      if [[ "$VERIFY_HOST" == "local" ]]; then
        "cmd_$cmd" "$@"
      else
        remote "$cmd $*"
      fi
      ;;
    *) sed -n '2,24p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 2 ;;
  esac
}

main "$@"
